import { isSafeSourceUrl } from '$lib/source-url'

export const fields = ['script', 'ids', 'description', 'place', 'url', 'title', 'author', 'publisher', 'year', 'page', 'note'] as const
export type Evidence = Record<typeof fields[number], string | null>
const limits = { script: 80, ids: 200, description: 5000, place: 500, url: 1000, title: 300, author: 300, publisher: 300, year: 40, page: 80, note: 5000 }

export function evidenceErrors(form: FormData): Partial<Record<typeof fields[number], string>> {
  const errors: Partial<Record<typeof fields[number], string>> = {}
  for (const name of fields) {
    const probe = new FormData()
    probe.set('script', 'Han')
    const url = form.get('url')
    probe.set('url', name === 'place' && typeof url === 'string' && isSafeSourceUrl(url.trim()) && url.trim().length <= limits.url ? url : 'https://example.org/')
    const value = form.get(name)
    if (value !== null) probe.set(name, value)
    else probe.delete(name)
    if (!readEvidence(probe)) errors[name] = name === 'script' ? 'Enter a script (up to 80 characters).'
      : name === 'url' ? 'Enter a valid HTTP or HTTPS URL (up to 1000 characters).'
      : name === 'place' ? 'Use up to 500 characters, or the current source URL. If the URL changed, clear or shorten the previous URL here.'
      : 'Check the length of this field.'
  }
  return errors
}

export function readEvidence(form: FormData): Evidence | null {
  const row = {} as Evidence
  for (const name of fields) {
    const value = form.get(name)
    if (value !== null && typeof value !== 'string') return null
    const text = (value ?? '').normalize('NFC').trim()
    // Place may contain the URL fallback generated by an earlier submission.
    const url = form.get('url')
    const isUrlFallback = name === 'place' && typeof url === 'string' && text === url.normalize('NFC').trim() && text.length <= limits.url
    if (text.length > limits[name] && !isUrlFallback) return null
    row[name] = text || null
  }
  if (!row.script || !row.url) return null
  if (!isSafeSourceUrl(row.url)) return null
  row.place ||= row.url
  if (!row.place) return null
  return row
}
